def plural_months(n: int) -> str:
    if n % 10 == 1 and n % 100 != 11:
        return f"{n} месяц"
    if 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14:
        return f"{n} месяца"
    return f"{n} месяцев"


